std::string ext_lower(const std::filesystem::path& p) {
    std::string e = p.extension().string();
    std::transform(e.begin(), e.end(), e.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return e;
}

bool is_stl(const Body& b) {
    return b.kind == Body::Kind::File && ext_lower(b.file) == ".stl";
}

// Path as a .geo string literal (forward slashes, escaped quotes).
std::string geo_path(const std::filesystem::path& p) {
    std::string s = std::filesystem::absolute(p).generic_string();
    std::string out;
    for (const char c : s) {
        if (c == '"' || c == '\\') {
            out += '\\';
        }
        out += c;
    }
    return "\"" + out + "\"";
}

struct Box3 {
    Vec3 lo;
    Vec3 hi;
};

// Conservative axis-aligned bounds of a primitive body.
Box3 body_bounds(const Body& b) {
    switch (b.kind) {
    case Body::Kind::Box:
        return {b.a.cwiseMin(b.b), b.a.cwiseMax(b.b)};
    case Body::Kind::Sphere:
        return {b.a - Vec3::Constant(b.radius), b.a + Vec3::Constant(b.radius)};
    case Body::Kind::Cylinder: {
        const Vec3 e = b.a + b.b;
        return {b.a.cwiseMin(e) - Vec3::Constant(b.radius),
                b.a.cwiseMax(e) + Vec3::Constant(b.radius)};
    }
    case Body::Kind::File:
        break;
    }
    const Scalar inf = std::numeric_limits<Scalar>::max() / 4;
    return {Vec3::Constant(-inf), Vec3::Constant(inf)};
}

class GeoWriter {
public:
    explicit GeoWriter(const GeometrySpec& s) : s_(s) {
        os_ << std::setprecision(17);
        const Vec3 ext = s.domain_max - s.domain_min;
        eps_ = 1e-6 * std::max(ext.norm(), 1e-12);
    }

    std::string run() {
        validate();
        os_ << "// Generated by cfd::geometry::write_geo - do not edit\n";
        os_ << "General.Terminal = 1;\n";
        if (s_.internal) {
            internal_geometry();
        } else if (std::any_of(s_.bodies.begin(), s_.bodies.end(), is_stl)) {
            stl_geometry();
        } else if (s_.two_d) {
            planar_geometry();
        } else {
            solid_geometry();
        }
        mesh_options();
        if (s_.two_d) {
            os_ << "Extrude {0, 0, " << (s_.domain_max.z() - s_.domain_min.z())
                << "} { Surface{:}; Layers{1}; Recombine; }\n";
        }
        physical_groups();
        os_ << "Mesh.ElementOrder = 1;\nMesh.MshFileVersion = 4.1;\nMesh.Binary = 0;\n";
        return os_.str();
    }

private:
    void validate() const {
        if (s_.internal) {
            if (s_.bodies.size() != 1 || s_.bodies[0].kind != Body::Kind::File ||
                is_stl(s_.bodies[0])) {
                throw std::invalid_argument(
                    "write_geo: internal flow needs exactly one STEP file body (the fluid volume)");
            }
            if (s_.two_d) {
                throw std::invalid_argument("write_geo: internal flow cannot be two_d");
            }
        } else if (!((s_.domain_max - s_.domain_min).minCoeff() > 0.0)) {
            throw std::invalid_argument("write_geo: domain_max must exceed domain_min");
        }
        if (!(s_.size > 0.0)) {
            throw std::invalid_argument("write_geo: size must be positive");
        }
        const bool stl = std::any_of(s_.bodies.begin(), s_.bodies.end(), is_stl);
        for (const Body& b : s_.bodies) {
            if (s_.two_d && b.kind != Body::Kind::Box && b.kind != Body::Kind::Cylinder) {
                throw std::invalid_argument(
                    "write_geo: two_d supports box and cylinder bodies only");
            }
            if (stl && !is_stl(b)) {
                throw std::invalid_argument(
                    "write_geo: STL bodies cannot be mixed with other bodies (use STEP instead)");
            }
            if ((b.kind == Body::Kind::Cylinder || b.kind == Body::Kind::Sphere) &&
                !(b.radius > 0.0)) {
                throw std::invalid_argument("write_geo: body radius must be positive");
            }
            if (b.kind == Body::Kind::File && b.file.empty()) {
                throw std::invalid_argument("write_geo: file body without a file name");
            }
            if (b.solid && (stl || s_.internal)) {
                throw std::invalid_argument("write_geo: solid bodies need STEP or primitive bodies "
                                            "(no STL, no internal flow)");
            }
            if (b.solid && (b.patch.empty() || b.patch == "fluid")) {
                throw std::invalid_argument(
                    "write_geo: solid body needs a name (patch) other than 'fluid'");
            }
        }
        for (std::size_t i = 0; i < s_.bodies.size(); ++i) {
            for (std::size_t j = i + 1; j < s_.bodies.size(); ++j) {
                if (s_.bodies[i].solid && s_.bodies[j].solid &&
                    s_.bodies[i].patch == s_.bodies[j].patch) {
                    throw std::invalid_argument("write_geo: solid body names must be unique");
                }
            }
        }
        if (s_.bl_layers > 0 && !s_.two_d && (s_.internal || has_solids() || s_.bodies.empty())) {
            throw std::invalid_argument("write_geo: 3D boundary layers need external flow with "
                                        "(non-solid) bodies");
        }
        if (s_.bl_layers > 0 && !(s_.bl_first > 0.0 && s_.bl_ratio >= 1.0)) {
            throw std::invalid_argument(
                "write_geo: boundary layer needs bl_first > 0, bl_ratio >= 1");
        }
    }

    void bbox(const Vec3& lo, const Vec3& hi) {
        os_ << lo.x() - eps_ << ", " << lo.y() - eps_ << ", " << lo.z() - eps_ << ", "
            << hi.x() + eps_ << ", " << hi.y() + eps_ << ", " << hi.z() + eps_;
    }

    [[nodiscard]] bool has_solids() const {
        return std::any_of(s_.bodies.begin(), s_.bodies.end(),
                           [](const Body& b) { return b.solid; });
    }

    // Bounding box arguments of solid body i ("x0, y0, z0, x1, y1, z1" with tolerance); in 2D
    // `extruded` spans the final z range, otherwise the sketch plane.
    [[nodiscard]] std::string solid_bbox(std::size_t i, bool extruded) const {
        const Body& b = s_.bodies[i];
        std::ostringstream o;
        o << std::setprecision(17);
        if (b.kind == Body::Kind::File) {
            o << "bb" << i << "(0) - " << eps_ << ", bb" << i << "(1) - " << eps_ << ", bb" << i
              << "(2) - " << eps_ << ", bb" << i << "(3) + " << eps_ << ", bb" << i << "(4) + "
              << eps_ << ", bb" << i << "(5) + " << eps_;
            return o.str();
        }
        Box3 bb = body_bounds(b);
        if (s_.two_d) {
            bb.lo.z() = s_.domain_min.z();
            bb.hi.z() = extruded ? z_top() : s_.domain_min.z();
        }
        o << bb.lo.x() - eps_ << ", " << bb.lo.y() - eps_ << ", " << bb.lo.z() - eps_ << ", "
          << bb.hi.x() + eps_ << ", " << bb.hi.y() + eps_ << ", " << bb.hi.z() + eps_;
        return o.str();
    }

    // z-extent of the final (extruded) geometry.
    [[nodiscard]] Scalar z_top() const { return s_.domain_max.z(); }

    void planar_geometry() {
        const Vec3& lo = s_.domain_min;
        const Vec3 ext = s_.domain_max - s_.domain_min;
        os_ << "SetFactory(\"OpenCASCADE\");\n";
        os_ << "Rectangle(1) = {" << lo.x() << ", " << lo.y() << ", " << lo.z() << ", " << ext.x()
            << ", " << ext.y() << "};\n";
        int tag = 2;
        auto shape = [&](const Body& b) {
            if (b.kind == Body::Kind::Cylinder) {
                os_ << "Disk(" << tag << ") = {" << b.a.x() << ", " << b.a.y() << ", " << lo.z()
                    << ", " << b.radius << "};\n";
            } else {
                const Vec3 bl = b.a.cwiseMin(b.b);
                const Vec3 bh = b.a.cwiseMax(b.b);
                os_ << "Rectangle(" << tag << ") = {" << bl.x() << ", " << bl.y() << ", " << lo.z()
                    << ", " << bh.x() - bl.x() << ", " << bh.y() - bl.y() << "};\n";
            }
            return tag++;
        };
        os_ << "tools() = {};\nsolids() = {};\n";
        for (const Body& b : s_.bodies) {
            if (!b.solid) {
                const int t = shape(b);
                os_ << "tools() += {" << t << "};\n";
            }
        }
        if (std::any_of(s_.bodies.begin(), s_.bodies.end(),
                        [](const Body& b) { return !b.solid; })) {
            os_ << "BooleanDifference{ Surface{1}; Delete; }{ Surface{tools()}; Delete; }\n";
        }
        if (has_solids()) {
            os_ << "fluid_s() = Surface{:};\n";
            for (const Body& b : s_.bodies) {
                if (b.solid) {
                    const int t = shape(b);
                    os_ << "solids() += {" << t << "};\n";
                }
            }
            os_ << "BooleanFragments{ Surface{fluid_s()}; Delete; }{ Surface{solids()}; Delete; "
                   "}\n";
        }
        // Curves on the domain rectangle vs. body curves (for sizing / boundary layers).
        const Vec3& hi = s_.domain_max;
        const Vec3 lo2(lo.x(), lo.y(), lo.z());
        const Vec3 hi2(hi.x(), hi.y(), lo.z());
        os_ << "dom_c() = Curve In BoundingBox{";
        bbox(lo2, Vec3(lo.x(), hi.y(), lo.z()));
        os_ << "};\ndom_c() += Curve In BoundingBox{";
        bbox(Vec3(hi.x(), lo.y(), lo.z()), hi2);
        os_ << "};\ndom_c() += Curve In BoundingBox{";
        bbox(lo2, Vec3(hi.x(), lo.y(), lo.z()));
        os_ << "};\ndom_c() += Curve In BoundingBox{";
        bbox(Vec3(lo.x(), hi.y(), lo.z()), hi2);
        os_ << "};\nbody_c() = Curve{:};\nbody_c() -= dom_c();\n";
        refinement("Curves", "body_c()");
        // Boundary layers on the obstacles only (not on fluid/solid interfaces).
        os_ << "bl_c() = body_c();\n";
        for (std::size_t i = 0; i < s_.bodies.size(); ++i) {
            if (s_.bodies[i].solid) {
                os_ << "bl_c() -= Curve In BoundingBox{" << solid_bbox(i, false) << "};\n";
            }
        }
        if (s_.bl_layers > 0) {
            const Scalar r = s_.bl_ratio;
            const Scalar n = static_cast<Scalar>(s_.bl_layers);
            const Scalar thickness = r > 1.0 + 1e-12
                                         ? s_.bl_first * (std::pow(r, n) - 1.0) / (r - 1.0)
                                         : s_.bl_first * n;
            os_ << "Field[3] = BoundaryLayer;\nField[3].CurvesList = {bl_c()};\n"
                << "Field[3].Size = " << s_.bl_first << ";\nField[3].Ratio = " << r << ";\n"
                << "Field[3].Thickness = " << thickness
                << ";\nField[3].Quads = " << (s_.quads ? 1 : 0) << ";\nBoundaryLayer Field = 3;\n";
        }
        if (s_.quads) {
            os_ << "Mesh.RecombineAll = 1;\n";
        }
    }

    void solid_geometry() {
        const Vec3& lo = s_.domain_min;
        const Vec3 ext = s_.domain_max - s_.domain_min;
        os_ << "SetFactory(\"OpenCASCADE\");\n";
        os_ << "Box(1) = {" << lo.x() << ", " << lo.y() << ", " << lo.z() << ", " << ext.x() << ", "
            << ext.y() << ", " << ext.z() << "};\n";
        os_ << "tools() = {};\nsolids() = {};\n";
        int tag = 2;
        std::size_t index = 0;
        for (const Body& b : s_.bodies) {
            const std::string list = b.solid ? "solids" : "tools";
            const std::size_t i = index++;
            switch (b.kind) {
            case Body::Kind::Box: {
                const Vec3 bl = b.a.cwiseMin(b.b);
                const Vec3 be = b.a.cwiseMax(b.b) - bl;
                os_ << "Box(" << tag << ") = {" << bl.x() << ", " << bl.y() << ", " << bl.z()
                    << ", " << be.x() << ", " << be.y() << ", " << be.z() << "};\n";
                os_ << list << "() += {" << tag << "};\n";
                break;
            }
            case Body::Kind::Cylinder:
                os_ << "Cylinder(" << tag << ") = {" << b.a.x() << ", " << b.a.y() << ", "
                    << b.a.z() << ", " << b.b.x() << ", " << b.b.y() << ", " << b.b.z() << ", "
                    << b.radius << "};\n";
                os_ << list << "() += {" << tag << "};\n";
                break;
            case Body::Kind::Sphere:
                os_ << "Sphere(" << tag << ") = {" << b.a.x() << ", " << b.a.y() << ", " << b.a.z()
                    << ", " << b.radius << "};\n";
                os_ << list << "() += {" << tag << "};\n";
                break;
            case Body::Kind::File:
                os_ << "sf" << i << "() = ShapeFromFile(" << geo_path(b.file) << ");\n"
                    << list << "() += sf" << i << "();\n";
                if (b.solid) {
                    os_ << "bb" << i << "() = BoundingBox Volume{sf" << i << "(0)};\n";
                }
                break;
            }
            ++tag;
        }
        if (std::any_of(s_.bodies.begin(), s_.bodies.end(),
                        [](const Body& b) { return !b.solid; })) {
            os_ << "BooleanDifference{ Volume{1}; Delete; }{ Volume{tools()}; Delete; }\n";
        }
        if (has_solids()) {
            os_ << "fluid_v() = Volume{:};\nfluid_v() -= {solids()};\n"
                << "BooleanFragments{ Volume{fluid_v()}; Delete; }{ Volume{solids()}; Delete; }\n";
        }
        domain_faces();
        os_ << "body_s() = Surface{:};\nbody_s() -= {s_dom()};\n";
        refinement("Surfaces", "body_s()");
    }

    void stl_geometry() {
        os_ << "stl_all() = {};\n";
        for (std::size_t i = 0; i < s_.bodies.size(); ++i) {
            os_ << "Merge " << geo_path(s_.bodies[i].file) << ";\n";
        }
        os_ << "ClassifySurfaces{40 * Pi / 180, 1, 1, Pi};\nCreateGeometry;\n"
            << "stl_all() = Surface{:};\n";
        // Domain box in the built-in kernel.
        const Vec3& lo = s_.domain_min;
        const Vec3& hi = s_.domain_max;
        const Vec3 c[8] = {{lo.x(), lo.y(), lo.z()}, {hi.x(), lo.y(), lo.z()},
                           {hi.x(), hi.y(), lo.z()}, {lo.x(), hi.y(), lo.z()},
                           {lo.x(), lo.y(), hi.z()}, {hi.x(), lo.y(), hi.z()},
                           {hi.x(), hi.y(), hi.z()}, {lo.x(), hi.y(), hi.z()}};
        for (int i = 0; i < 8; ++i) {
            os_ << "bp" << i << " = newp; Point(bp" << i << ") = {" << c[i].x() << ", " << c[i].y()
                << ", " << c[i].z() << "};\n";
        }
        const int edges[12][2] = {{0, 1}, {1, 2}, {2, 3}, {3, 0}, {4, 5}, {5, 6},
                                  {6, 7}, {7, 4}, {0, 4}, {1, 5}, {2, 6}, {3, 7}};
        for (int i = 0; i < 12; ++i) {
            os_ << "bl" << i << " = newl; Line(bl" << i << ") = {bp" << edges[i][0] << ", bp"
                << edges[i][1] << "};\n";
        }
        // Faces as signed edge loops.
        const char* loops[6] = {"bl3, bl8, -bl7, -bl11", "bl1, bl10, -bl5, -bl9",
                                "bl0, bl9, -bl4, -bl8",  "-bl2, bl10, bl6, -bl11",
                                "bl0, bl1, bl2, bl3",    "bl4, bl5, bl6, bl7"};
        os_ << "box_s() = {};\n";
        for (int i = 0; i < 6; ++i) {
            os_ << "bc" << i << " = newcl; Curve Loop(bc" << i << ") = {" << loops[i] << "};\nbs"
                << i << " = news; Plane Surface(bs" << i << ") = {bc" << i << "};\nbox_s() += {bs"
                << i << "};\n";
        }
        os_ << "sl_box = newsl; Surface Loop(sl_box) = {box_s()};\n"
            << "sl_stl = newsl; Surface Loop(sl_stl) = {stl_all()};\n"
            << "fluid = newv; Volume(fluid) = {sl_box, sl_stl};\n";
        domain_faces();
        os_ << "body_s() = stl_all();\n";
        refinement("Surfaces", "body_s()");
    }

    void internal_geometry() {
        os_ << "SetFactory(\"OpenCASCADE\");\nfluid() = ShapeFromFile("
            << geo_path(s_.bodies[0].file) << ");\nbody_s() = Surface{:};\ns_dom() = {};\n";
        refinement("Surfaces", "body_s()");
    }

    void domain_faces() {
        const Vec3& lo = s_.domain_min;
        const Vec3 hi(s_.domain_max.x(), s_.domain_max.y(), z_top());
        const Vec3 face_lo[6] = {lo, {hi.x(), lo.y(), lo.z()}, lo, {lo.x(), hi.y(), lo.z()},
                                 lo, {lo.x(), lo.y(), hi.z()}};
        const Vec3 face_hi[6] = {{lo.x(), hi.y(), hi.z()}, hi, {hi.x(), lo.y(), hi.z()}, hi,
                                 {hi.x(), hi.y(), lo.z()}, hi};
        os_ << "s_dom() = {};\n";
        for (int i = 0; i < 6; ++i) {
            os_ << "s_face" << i << "() = Surface In BoundingBox{";
            bbox(face_lo[i], face_hi[i]);
            os_ << "};\ns_dom() += {s_face" << i << "()};\n";
        }
    }

    void refinement(const char* what, const char* list) {
        if (!(s_.size_near > 0.0) || s_.size_near >= s_.size) {
            os_ << "Mesh.MeshSizeMax = " << s_.size << ";\n";
            return;
        }
        const Scalar dist = s_.refine_distance > 0.0 ? s_.refine_distance : 10.0 * s_.size_near;
        os_ << "Field[1] = Distance;\nField[1]." << what << "List = {" << list
            << "};\nField[1].Sampling = 100;\n"
            << "Field[2] = Threshold;\nField[2].InField = 1;\nField[2].SizeMin = " << s_.size_near
            << ";\nField[2].SizeMax = " << s_.size << ";\nField[2].DistMin = 0;\n"
            << "Field[2].DistMax = " << dist << ";\nBackground Field = 2;\n"
            << "Mesh.MeshSizeExtendFromBoundary = 0;\nMesh.MeshSizeFromPoints = 0;\n"
            << "Mesh.MeshSizeFromCurvature = 0;\nMesh.MeshSizeMax = " << s_.size << ";\n";
    }

    void mesh_options() { os_ << "Mesh.Optimize = 1;\n"; }

    // Collects surface lists per patch name; one physical group per unique name.
    void add_to_group(const std::string& name, const std::string& list) {
        auto it = std::find(group_names_.begin(), group_names_.end(), name);
        std::size_t idx = static_cast<std::size_t>(it - group_names_.begin());
        if (it == group_names_.end()) {
            group_names_.push_back(name);
            os_ << "g" << idx << "() = {};\n";
        }
        os_ << "g" << idx << "() += {" << list << "};\n";
    }

    void physical_groups() {
        // After extrusion (two_d) the domain faces are recomputed on the final solid.
        if (s_.two_d) {
            domain_faces();
        }
        // Explicit selectors first; they take faces away from the default groups.
        os_ << "s_sel_all() = {};\n";
        for (std::size_t i = 0; i < s_.patches.size(); ++i) {
            const PatchSelector& p = s_.patches[i];
            os_ << "s_sel" << i << "() = Surface In BoundingBox{";
            bbox(p.min.cwiseMin(p.max), p.min.cwiseMax(p.max));
            os_ << "};\ns_sel" << i << "() -= {s_sel_all()};\ns_sel_all() += {s_sel" << i
                << "()};\n";
            add_to_group(p.name, "s_sel" + std::to_string(i) + "()");
        }
        if (!s_.internal) {
            for (int i = 0; i < 6; ++i) {
                os_ << "s_face" << i << "() -= {s_sel_all()};\n";
                add_to_group(s_.domain_patch_names[static_cast<std::size_t>(i)],
                             "s_face" + std::to_string(i) + "()");
            }
        }
        // Body surfaces: assigned by body bounds in order; the rest to the first body / "walls".
        os_ << "s_rest() = Surface{:};\ns_rest() -= {s_dom()};\ns_rest() -= {s_sel_all()};\n"
            << "s_claimed() = {};\n";
        // Surfaces of solid bodies are fluid/solid interfaces (internal faces): no patch.
        for (std::size_t i = 0; i < s_.bodies.size(); ++i) {
            if (s_.bodies[i].solid) {
                os_ << "s_rest() -= Surface In BoundingBox{" << solid_bbox(i, true) << "};\n"
                    << "s_claimed() += Surface In BoundingBox{" << solid_bbox(i, true) << "};\n"
                    << "s_claimed() -= {s_dom()};\n";
            }
        }
        if (s_.internal) {
            add_to_group("walls", "s_rest()");
        } else {
            for (std::size_t i = 0; i < s_.bodies.size(); ++i) {
                const Body& b = s_.bodies[i];
                if (b.kind == Body::Kind::File || b.solid) {
                    continue;
                }
                Box3 bb = body_bounds(b);
                if (s_.two_d) {
                    bb.lo.z() = s_.domain_min.z();
                    bb.hi.z() = z_top();
                }
                os_ << "s_body" << i << "() = Surface In BoundingBox{";
                bbox(bb.lo, bb.hi);
                os_ << "};\ns_body" << i << "() -= {s_dom()};\ns_body" << i
                    << "() -= {s_sel_all()};\ns_body" << i << "() -= {s_claimed()};\n";
                os_ << "s_rest() -= {s_body" << i << "()};\ns_claimed() += {s_body" << i
                    << "()};\n";
                add_to_group(b.patch, "s_body" + std::to_string(i) + "()");
            }
            std::string rest_name = "obstacle";
            for (const Body& b : s_.bodies) {
                if (!b.solid) {
                    rest_name = b.patch;
                    break;
                }
            }
            add_to_group(rest_name, "s_rest()");
        }
        for (std::size_t g = 0; g < group_names_.size(); ++g) {
            os_ << "If (#g" << g << "() > 0)\n  Physical Surface(\"" << group_names_[g]
                << "\") = {g" << g << "()};\nEndIf\n";
        }
        os_ << "v_fluid() = Volume{:};\n";
        for (std::size_t i = 0; i < s_.bodies.size(); ++i) {
            if (s_.bodies[i].solid) {
                os_ << "v_sol" << i << "() = Volume In BoundingBox{" << solid_bbox(i, true)
                    << "};\nv_fluid() -= {v_sol" << i << "()};\nPhysical Volume(\""
                    << s_.bodies[i].patch << "\") = {v_sol" << i << "()};\n";
            }
        }
        os_ << "Physical Volume(\"fluid\") = {v_fluid()};\n";
    }

    const GeometrySpec& s_;
    std::ostringstream os_;
    std::vector<std::string> group_names_;
    Scalar eps_ = 1e-9;
};

std::string quote_arg(const std::string& s) {
    return "\"" + s + "\"";
}

// Environment variable or empty (MSVC deprecates std::getenv).
std::string env_var(const char* name) {
#ifdef _MSC_VER
    char* buffer = nullptr;
    std::size_t size = 0;
    if (_dupenv_s(&buffer, &size, name) != 0 || buffer == nullptr) {
        return {};
    }
    std::string value(buffer);
    std::free(buffer);
    return value;
#else
    const char* value = std::getenv(name);
    return value != nullptr ? value : "";
#endif
}

std::string read_tail(const std::filesystem::path& file, std::size_t max_chars) {
    std::ifstream in(file);
    std::stringstream ss;
    ss << in.rdbuf();
    const std::string text = ss.str();
    return text.size() > max_chars ? text.substr(text.size() - max_chars) : text;
}

