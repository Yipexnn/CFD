// 3D prism boundary layers (two Gmsh runs):
//  1. body_surface_geo: surface mesh of every body (OpenCASCADE primitives / STEP, or the
//     STL triangles), exported as one STL solid per body;
//  2. layered_fluid_geo: the body STLs are merged as discrete surfaces and extruded along
//     their normals in bl_layers prism layers (Gmsh boundary-layer extrusion); the domain box
//     (built-in kernel) minus the layer tops is filled with tetrahedra.
bool bl3d(const GeometrySpec& s) {
    return s.bl_layers > 0 && !s.two_d;
}

std::string body_surface_geo(const GeometrySpec& s) {
    (void)GeoWriter(s).run(); // validation only
    std::ostringstream os;
    os << std::setprecision(17);
    os << "// Generated by cfd::geometry (3D boundary layers, body surfaces) - do not edit\n"
       << "General.Terminal = 1;\nSetFactory(\"OpenCASCADE\");\n";
    int tag = 1;
    for (std::size_t i = 0; i < s.bodies.size(); ++i) {
        const Body& b = s.bodies[i];
        switch (b.kind) {
        case Body::Kind::Box: {
            const Vec3 lo = b.a.cwiseMin(b.b);
            const Vec3 e = b.a.cwiseMax(b.b) - lo;
            os << "Box(" << tag << ") = {" << lo.x() << ", " << lo.y() << ", " << lo.z() << ", "
               << e.x() << ", " << e.y() << ", " << e.z() << "};\n";
            os << "s" << i << "() = Boundary{ Volume{" << tag << "}; };\n";
            break;
        }
        case Body::Kind::Cylinder:
            os << "Cylinder(" << tag << ") = {" << b.a.x() << ", " << b.a.y() << ", " << b.a.z()
               << ", " << b.b.x() << ", " << b.b.y() << ", " << b.b.z() << ", " << b.radius
               << "};\n";
            os << "s" << i << "() = Boundary{ Volume{" << tag << "}; };\n";
            break;
        case Body::Kind::Sphere:
            os << "Sphere(" << tag << ") = {" << b.a.x() << ", " << b.a.y() << ", " << b.a.z()
               << ", " << b.radius << "};\n";
            os << "s" << i << "() = Boundary{ Volume{" << tag << "}; };\n";
            break;
        case Body::Kind::File:
            if (is_stl(b)) {
                os << "pre" << i << "() = Surface{:};\nMerge " << geo_path(b.file) << ";\ns" << i
                   << "() = Surface{:};\ns" << i << "() -= pre" << i << "();\n";
            } else {
                os << "v" << i << "() = ShapeFromFile(" << geo_path(b.file) << ");\ns" << i
                   << "() = Boundary{ Volume{v" << i << "()}; };\n";
            }
            break;
        }
        ++tag;
    }
    for (std::size_t i = 0; i < s.bodies.size(); ++i) {
        os << "Physical Surface(\"body" << i << "\", " << 101 + i << ") = {s" << i << "()};\n";
    }
    const Scalar near = s.size_near > 0.0 ? s.size_near : s.size;
    os << "Mesh.MeshSizeMax = " << near << ";\nMesh.MeshSizeFromCurvature = 12;\n"
       << "Mesh.StlOneSolidPerSurface = 2;\n";
    return os.str();
}

std::string layered_fluid_geo(const GeometrySpec& s, const std::string& body_stl) {
    std::ostringstream os;
    os << std::setprecision(17);
    os << "// Generated by cfd::geometry (3D boundary layers, fluid) - do not edit\n"
       << "General.Terminal = 1;\nMerge " << body_stl << ";\nCreateTopology;\n"
       << "Geometry.ExtrudeReturnLateralEntities = 0;\nvols() = {};\nloops() = {};\n"
       << "tops() = {};\n";
    // Cumulative layer heights.
    std::ostringstream counts;
    std::ostringstream heights;
    heights << std::setprecision(17);
    Scalar h = 0.0;
    Scalar d = s.bl_first;
    for (int k = 0; k < s.bl_layers; ++k) {
        h += d;
        d *= s.bl_ratio;
        counts << (k > 0 ? ", " : "") << 1;
        heights << (k > 0 ? ", " : "") << h;
    }
    for (std::size_t i = 0; i < s.bodies.size(); ++i) {
        os << "out() = Extrude{ Surface{" << i + 1 << "}; Layers{ {" << counts.str() << "}, {"
           << heights.str() << "} }; Recombine; };\nt() = {};\n"
           << "For k In {0:#out()-1:2}\n  t() += out(k); vols() += out(k+1);\nEndFor\n"
           << "Surface Loop(" << 9101 + i << ") = {t()};\nloops() += " << 9101 + i
           << ";\ntops() += t();\n";
    }
    const Vec3& lo = s.domain_min;
    const Vec3& hi = s.domain_max;
    os << "lc = " << s.size << ";\n";
    const std::array<Vec3, 8> p{Vec3(lo.x(), lo.y(), lo.z()), Vec3(hi.x(), lo.y(), lo.z()),
                                Vec3(hi.x(), hi.y(), lo.z()), Vec3(lo.x(), hi.y(), lo.z()),
                                Vec3(lo.x(), lo.y(), hi.z()), Vec3(hi.x(), lo.y(), hi.z()),
                                Vec3(hi.x(), hi.y(), hi.z()), Vec3(lo.x(), hi.y(), hi.z())};
    for (std::size_t k = 0; k < 8; ++k) {
        os << "Point(" << 9001 + k << ") = {" << p[k].x() << ", " << p[k].y() << ", " << p[k].z()
           << ", lc};\n";
    }
    os << "Line(9001) = {9001, 9002}; Line(9002) = {9002, 9003}; Line(9003) = {9003, 9004};\n"
          "Line(9004) = {9004, 9001}; Line(9005) = {9005, 9006}; Line(9006) = {9006, 9007};\n"
          "Line(9007) = {9007, 9008}; Line(9008) = {9008, 9005}; Line(9009) = {9001, 9005};\n"
          "Line(9010) = {9002, 9006}; Line(9011) = {9003, 9007}; Line(9012) = {9004, 9008};\n"
          "Curve Loop(9001) = {9001, 9002, 9003, 9004}; Plane Surface(9001) = {9001};\n"
          "Curve Loop(9002) = {9005, 9006, 9007, 9008}; Plane Surface(9002) = {9002};\n"
          "Curve Loop(9003) = {9001, 9010, -9005, -9009}; Plane Surface(9003) = {9003};\n"
          "Curve Loop(9004) = {9002, 9011, -9006, -9010}; Plane Surface(9004) = {9004};\n"
          "Curve Loop(9005) = {9003, 9012, -9007, -9011}; Plane Surface(9005) = {9005};\n"
          "Curve Loop(9006) = {9004, 9009, -9008, -9012}; Plane Surface(9006) = {9006};\n"
          "Surface Loop(9001) = {9001, 9002, 9003, 9004, 9005, 9006};\n"
          "Volume(9001) = {9001, loops()};\n";
    // Box faces: xmin, xmax, ymin, ymax, zmin, zmax.
    const std::array<int, 6> face{9006, 9004, 9003, 9005, 9001, 9002};
    std::map<std::string, std::vector<std::string>> groups;
    for (std::size_t k = 0; k < 6; ++k) {
        groups[s.domain_patch_names[k]].push_back(std::to_string(face[k]));
    }
    for (std::size_t i = 0; i < s.bodies.size(); ++i) {
        groups[s.bodies[i].patch].push_back(std::to_string(i + 1));
    }
    for (const auto& [name, list] : groups) {
        os << "Physical Surface(\"" << name << "\") = {";
        for (std::size_t k = 0; k < list.size(); ++k) {
            os << (k > 0 ? ", " : "") << list[k];
        }
        os << "};\n";
    }
    os << "Physical Volume(\"fluid\") = {vols(), 9001};\n";
    if (s.size_near > 0.0 && s.refine_distance > 0.0) {
        os << "Field[1] = Distance;\nField[1].SurfacesList = {tops()};\n"
           << "Field[2] = Threshold;\nField[2].InField = 1;\nField[2].SizeMin = " << s.size_near
           << ";\nField[2].SizeMax = " << s.size << ";\nField[2].DistMin = 0;\n"
           << "Field[2].DistMax = " << s.refine_distance << ";\nBackground Field = 2;\n";
    }
    os << "Mesh.MeshSizeMax = " << s.size << ";\nMesh.Format = 1;\nMesh.MshFileVersion = 4.1;\n";
    return os.str();
}

std::string write_geo(const GeometrySpec& spec) {
    if (bl3d(spec)) {
        (void)GeoWriter(spec).run(); // validation
        return layered_fluid_geo(spec, "\"geometry_bodies.stl\"");
    }
    return GeoWriter(spec).run();
}

std::string find_gmsh() {
    if (std::string env = env_var("CFD_GMSH"); !env.empty()) {
        return env;
    }
#ifdef _WIN32
    const char sep = ';';
    const char* names[] = {"gmsh.exe"};
#else
    const char sep = ':';
    const char* names[] = {"gmsh"};
#endif
    std::stringstream ss(env_var("PATH"));
    std::string dir;
    while (std::getline(ss, dir, sep)) {
        for (const char* n : names) {
            const std::filesystem::path candidate = std::filesystem::path(dir) / n;
            std::error_code ec;
            if (!dir.empty() && std::filesystem::is_regular_file(candidate, ec)) {
                return candidate.string();
            }
        }
    }
    return {};
}

mesh::Mesh generate_mesh(const GeometrySpec& spec, const std::filesystem::path& work_dir,
                         const std::string& gmsh_executable) {
    if (gmsh_executable.empty()) {
        throw std::runtime_error(
            "Gmsh executable not found: install Gmsh (https://gmsh.info) and put it on PATH or "
            "set CFD_GMSH to its full path");
    }
    std::filesystem::create_directories(work_dir);
    const std::filesystem::path geo = work_dir / "geometry.geo";
    const std::filesystem::path msh = work_dir / "geometry.msh";
    const std::filesystem::path log = work_dir / "gmsh.log";
    {
        std::ofstream out(geo);
        if (!out) {
            throw std::runtime_error("generate_mesh: cannot write " + geo.string());
        }
        out << write_geo(spec);
    }
    std::filesystem::remove(msh);

    if (bl3d(spec)) {
        const std::filesystem::path bgeo = work_dir / "geometry_bodies.geo";
        const std::filesystem::path stl = work_dir / "geometry_bodies.stl";
        {
            std::ofstream out(bgeo);
            out << body_surface_geo(spec);
            std::ofstream fluid(geo);
            fluid << layered_fluid_geo(spec, geo_path(stl));
        }
        std::filesystem::remove(stl);
        std::string bcmd = quote_arg(gmsh_executable) + " " + quote_arg(bgeo.string()) + " -2 -o " +
                           quote_arg(stl.string()) + " > " + quote_arg(log.string()) + " 2>&1";
#ifdef _WIN32
        bcmd = "\"" + bcmd + "\"";
#endif
        const int brc = std::system(bcmd.c_str());
        if (brc != 0 || !std::filesystem::exists(stl)) {
            throw std::runtime_error("Gmsh failed on the body surfaces (exit code " +
                                     std::to_string(brc) + "):\n" + read_tail(log, 2000));
        }
    }

    std::string cmd = quote_arg(gmsh_executable) + " " + quote_arg(geo.string()) + " -3 -o " +
                      quote_arg(msh.string()) + " > " + quote_arg(log.string()) + " 2>&1";
#ifdef _WIN32
    cmd = "\"" + cmd + "\""; // cmd.exe strips one level of quotes
#endif
    const int rc = std::system(cmd.c_str());
    if (rc != 0 || !std::filesystem::exists(msh)) {
        throw std::runtime_error("Gmsh failed (exit code " + std::to_string(rc) + "):\n" +
                                 read_tail(log, 2000));
    }
    return read_generated_mesh(spec, work_dir);
}

mesh::Mesh read_generated_mesh(const GeometrySpec& spec, const std::filesystem::path& work_dir) {
    mesh::Mesh mesh = mesh::read_gmsh(work_dir / "geometry.msh");
    // Body surfaces are no-slip walls unless the name says otherwise.
    for (const Body& body : spec.bodies) {
        const mesh::Patch* patch = mesh.find_patch(body.patch);
        if (!body.solid && patch != nullptr && patch->type == mesh::PatchType::Patch) {
            mesh.set_patch_type(body.patch, mesh::PatchType::Wall);
        }
    }
    return mesh;
}

